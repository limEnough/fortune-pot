function ymd(d: Date): string {
  return `${d.getFullYear()}-${String(d.getMonth() + 1).padStart(2, "0")}-${String(d.getDate()).padStart(2, "0")}`;
}

/**
 * 오행 세력 집계. 월지는 계절(월령)을 쥐고 있어 3배, 일지는 일간의 자리라 2배로 본다.
 * 나머지 자리는 1. 시주를 모르면 시간·시지는 빠진다.
 */
function countOhaeng(s: SajuResult): Record<Ohaeng, number> {
  const c: Record<Ohaeng, number> = { 목: 0, 화: 0, 토: 0, 금: 0, 수: 0 };
  const g = (gan: number, w: number) => { c[ohOfGan(gan)] += w; };
  const j = (ji: number, w: number) => { c[ohOfJi(ji)] += w; };
  g(s.year[0], 1);  j(s.year[1], 1);
  g(s.month[0], 1); j(s.month[1], 3);   // 득령 — 가장 무겁게
  g(s.day[0], 1);   j(s.day[1], 2);     // 득지
  if (s.hour) { g(s.hour[0], 1); j(s.hour[1], 1); }
  return c;
}

/** 일간을 돕는 세력(비겁+인성)이 전체에서 차지하는 비중으로 신강/중화/신약을 가른다. */
function judgeShin(ilgan: number, c: Record<Ohaeng, number>): Shin {
  const d = ohIdxOfGan(ilgan);
  const at = (i: number) => c[OH_ORDER[i]];
  const support = at(d) + at((d + 4) % 5);        // 비겁 + 인성
  const total = OH_ORDER.reduce((a, o) => a + c[o], 0);
  const r = support / total;
  if (r >= 0.55) return "신강";
  if (r <= 0.35) return "신약";
  return "중화";
}

function weakestOh(c: Record<Ohaeng, number>): Ohaeng {
  let min: Ohaeng = "목"; let v = Infinity;
  OH_ORDER.forEach((k) => { if (c[k] < v) { v = c[k]; min = k; } });
  return min;
}
function strongestOh(c: Record<Ohaeng, number>): Ohaeng {
  let max: Ohaeng = "목"; let v = -1;
  OH_ORDER.forEach((k) => { if (c[k] > v) { v = c[k]; max = k; } });
  return max;
}

// 지지 육합: 자축·인해·묘술·진유·사신·오미 — 두 지지 합이 12로 나눠 1
const isYukhap = (a: number, b: number) => (a + b) % 12 === 1;
// 지지 육충: 자오·축미·인신·묘유·진술·사해 — 정확히 여섯 칸 차이
const isChung = (a: number, b: number) => Math.abs(a - b) === 6;

/**
 * 오늘 보충하면 좋은 오행 후보 3개.
 * 본명에서 부족한 오행일수록 앞에 오되, 오늘 간지가 그 오행을 생해 주면 순위가 올라간다.
 * → 후보 구성이 날마다 바뀌므로 색·아이템·숫자가 고정되지 않는다.
 */
function luckyCandidates(
  c: Record<Ohaeng, number>, todayGanOh: Ohaeng, todayJiOh: Ohaeng,
): Ohaeng[] {
  const total = OH_ORDER.reduce((a, o) => a + c[o], 0);
  const rank = (o: Ohaeng) => {
    const i = OH_IDX[o];
    let v = -(c[o] / total) * 10;                          // 부족할수록 높게
    if (OH_IDX[todayGanOh] === (i + 4) % 5) v += 1.5;      // 오늘 천간이 이 오행을 생함
    if (OH_IDX[todayJiOh] === (i + 4) % 5) v += 1.0;       // 오늘 지지가 이 오행을 생함
    if (todayGanOh === o) v += 0.6;                        // 오늘과 같은 기운
    if (todayJiOh === o) v += 0.4;
    return v;
  };
  return [...OH_ORDER].sort((a, b) => rank(b) - rank(a)).slice(0, 3);
}

/**
 * 사주(본명) × 오늘 일주의 관계로 일일 운세를 생성한다.
 *
 * 점수 구성
 *  1) 오늘 천간·지지 각각의 십성을 뽑아 6.5 : 3.5로 가중 합산 (지지도 점수에 반영)
 *  2) 십성 길흉표는 신강/중화/신약에 따라 분기 (용신 방향이 반대이므로)
 *  3) 오행 세력은 월지 3·일지 2 가중으로 집계해 강약 판정과 균형 보정에 사용
 *  4) 오늘 일지와 본명 일지의 육합(+)·육충(−)을 반영
 * 카테고리 점수도 같은 구조를 따르되, 카테고리를 주관하는 십성 그룹에 걸리면 가산한다.
 *
 * 문구는 두 축을 합성한다 — 앞 문장은 천간 십성(무엇이 오는가), 뒤 문장은
 * 지지 그룹(어떤 자리인가), 한마디는 일간 강약이 맡는다. 천간 10일 · 지지 12일 주기라
 * 두 축의 조합은 60일 주기이고, 그 안에서 다시 이름+날짜 해시가 하루치를 고른다.
 * 색·아이템·숫자는 보충 오행이 후보군을 정하고 같은 방식으로 하루치를 고른다.
 */
export function generateFortune(saju: SajuResult, name: string, date = new Date()): Fortune {
  const today = computeSaju(ymd(date), null);
  const todayGan = today.day[0];
  const todayZhi = today.day[1];

  const dayOh = ohIdxOfGan(saju.ilgan);
  const dayYang = isYangGan(saju.ilgan);

  // 오늘 천간·지지 각각의 십성
  const sip = sipseong(dayOh, dayYang, ohIdxOfGan(todayGan), isYangGan(todayGan));
  const jiSip = sipseong(dayOh, dayYang, ohIdxOfJi(todayZhi), isYangJi(todayZhi));

  const counts = countOhaeng(saju);
  const shin = judgeShin(saju.ilgan, counts);
  const weak = weakestOh(counts);
  const strong = strongestOh(counts);
  const todayGanOh = ohOfGan(todayGan);
  const todayJiOh = ohOfJi(todayZhi);

  const hap = isYukhap(todayZhi, saju.day[1]);
  const chung = isChung(todayZhi, saju.day[1]);

  // 오행 균형·합충 보정 — 종합과 카테고리가 함께 쓰는 공통 항
  const balance = (gw: number, jw: number) =>
    (todayGanOh === weak ? gw : todayGanOh === strong ? -gw : 0) +
    (todayJiOh === weak ? jw : todayJiOh === strong ? -jw : 0);

  const tbl = SIP_SCORE[shin];
  let raw = tbl[sip] * 0.65 + tbl[jiSip] * 0.35;
  raw += balance(0.5, 0.3);
  if (hap) raw += 0.4; else if (chung) raw -= 0.5;
  const sc = clamp15(raw);

  // 항목마다 다른 솔트를 써서 선택이 서로 얽히지 않게 한다
  const h = (salt: string) => fnv1a(salt + name + ymd(date));

  // 문구는 2단 합성 — 천간 십성이 '무엇이 오는가', 지지 그룹이 '어떤 자리인가'를 맡는다
  const jiGroup = GROUP_OF[jiSip];
  const line2 = (a: string[], b: string[], s1: string, s2: string) =>
    `${pick(a, h(s1))} ${pick(b, h(s2))}`;
  const overall = line2(OVERALL_LINES[sip], OVERALL_JI[jiGroup], "o", "oj");

  // 신강약 분기가 기본 길흉을 얼마나 틀었는지 — 카테고리에도 같은 방향으로 얹는다
  const shinDelta = tbl[sip] - SIP_SCORE.중화[sip];
  const catScore = (cat: CatKey) => {
    const t = CAT_SCORE[cat];
    let v = t[sip] * 0.65 + t[jiSip] * 0.35 + shinDelta * 0.35;
    // 주관 그룹에 걸리면 가산, 아니면 감산 — 기댓값이 0이 되게 해 카테고리가 위로 쏠리지 않도록
    v += CAT_FOCUS[cat].includes(GROUP_OF[sip]) ? 0.4 : -0.25;
    v += CAT_FOCUS[cat].includes(GROUP_OF[jiSip]) ? 0.3 : -0.2;
    v += balance(0.3, 0.2);
    if (hap) v += 0.3; else if (chung) v -= 0.4;
    return clamp15(v);
  };

  const categories: FortuneCategory[] = [
    { key: "애정운",       icon: "💕", score: catScore("애정"), line: line2(LOVE_LINES[sip], LOVE_JI[jiGroup], "l", "lj") },
    { key: "금전운",       icon: "💰", score: catScore("금전"), line: line2(MONEY_LINES[sip], MONEY_JI[jiGroup], "m", "mj") },
    { key: "직장·학업운", icon: "📚", score: catScore("직장"), line: line2(WORK_LINES[sip], WORK_JI[jiGroup], "w", "wj") },
    { key: "건강운",       icon: "🌿", score: catScore("건강"), line: line2(HEALTH_LINES[sip], HEALTH_JI[jiGroup], "t", "tj") },
  ];

  // 행운의 색·아이템·숫자: 오늘의 보충 오행 후보 3개 중 하나를 고르고, 그 안에서 다시 선택
  const cands = luckyCandidates(counts, todayGanOh, todayJiOh);
  const luckyOh = pick(cands, h("e"));
  const color = pick(OH_LUCKY_COLORS[luckyOh], h("c"));
  const item = pick(OH_LUCKY_ITEMS[luckyOh], h("i"));
  const number = pick(OH_NUMBERS[luckyOh], h("n"));

  const d = date;
  const dateLabel = `${d.getFullYear()}.${String(d.getMonth() + 1).padStart(2, "0")}.${String(d.getDate()).padStart(2, "0")} (${"일월화수목금토"[d.getDay()]})`;

  return {
    dateLabel,
    score: sc,
    grade: GRADE[sc - 1],
    overall,
    categories,
    color,
    number,
    item,
    advice: line2(ADVICE_LINES[sip], SHIN_ADVICE[shin], "a", "aj"),
    moodKey: SIP_MOOD[sip],
  };
}
